package com.capstone.mortgage.dto;

import com.capstone.mortgage.entity.Payment;
import jakarta.validation.constraints.DecimalMax;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.Digits;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;

import java.math.BigDecimal;
import java.time.LocalDate;

/**
 * POST /api/v1/mortgages/{id}/payments body.
 *
 * M6 Task 6.3 fix for VULN-M6-001 (mass assignment, OWASP API3): the endpoint used to bind the JSON body directly
 * onto the Payment JPA entity, so a client could send "id" of an existing payment and JPA would MERGE (overwrite) it.
 * Only these four client-controlled fields exist now; id and mortgage are always set by the server.
 */
public record PaymentRequest(
        @NotNull(message = "Due date is mandatory") LocalDate dueDate,
        LocalDate paidDate,
        @NotNull(message = "Amount is mandatory")
        @DecimalMin(value = "0.01", message = "Amount must be greater than zero")
        @DecimalMax(value = "10000000.00", message = "Amount must not exceed 10,000,000.00")
        @Digits(integer = 13, fraction = 2, message = "Amount must have at most 2 decimal places")
        BigDecimal amount,
        @NotBlank(message = "Status is mandatory")
        @Pattern(regexp = "SCHEDULED|POSTED|FAILED|REVERSED", message = "Status must be SCHEDULED, POSTED, FAILED, or REVERSED")
        String status
) {
    /** Always a NEW entity: id is generated by JPA, mortgage is attached by PaymentService. */
    public Payment toNewEntity() {
        Payment payment = new Payment();
        payment.setDueDate(dueDate);
        payment.setPaidDate(paidDate);
        payment.setAmount(amount);
        payment.setStatus(status);
        return payment;
    }
}
